// Control Structures

// The if control structure
let num1 = 20;
let num2 = 14;

if (num1 > num2) {
  console.log(`${num1} is greater than ${num2}`);
}


if (num1 < num2) {
  console.log(`$ {num1} is less than ${num2}`);
}


if (num2 > num1) {
  console.log(`$ {num2} is greater than ${num1}`);
}


